import { ChatGroq } from "@langchain/groq";
import { getApiKey } from "../../utils/file.util.js";
import {
  AIMessageChunk,
  BaseMessage,
  ToolMessage,
} from "@langchain/core/messages";
import * as fileTools from "../tools/files.tool.js";

// The state passed into every graph node contains the full message history.
interface stateFormat {
  messages: BaseMessage[];
}

/**
 * Runs the Groq-backed language model for the current conversation state.
 * It validates the API key, streams the reply, and appends the AI output to messages.
 */
export async function LLMNode(state: stateFormat) {
  // Load the saved API key before initializing the model client.
  const keyResult = await getApiKey();
  if (!keyResult || "error" in keyResult) {
    throw new Error(keyResult?.error ?? "API key not found");
  }

  // Create the Groq chat model with the stored credentials and bind available tools.
  const model = new ChatGroq({
    model: "openai/gpt-oss-120b",
    apiKey: keyResult.apiKey,
    temperature: 0.7,
  }).bindTools(Object.values(fileTools));

  // Stream the response from the current message list.
  const stream = await model.stream(state.messages);

  process.stdout.write("[AI]: ");

  // Accumulate the streamed chunks into a single AI message object.
  let aiMessage: AIMessageChunk | undefined;
  for await (const chunk of stream) {
    process.stdout.write(String(chunk.content));
    aiMessage = aiMessage ? aiMessage.concat(chunk) : chunk;
  }

  process.stdout.write("\n");

  // Add the AI response to the state so the conversation continues.
  return {
    messages: [...state.messages, aiMessage],
  };
}

/**
 * Executes any tool calls generated by the model in the latest AI response.
 * It invokes the matching tool and appends the result as a tool message.
 */
export async function ToolNode(state: stateFormat) {
  // Read the most recent AI message and extract any tool requests.
  const lastMessage = state.messages[
    state.messages.length - 1
  ] as AIMessageChunk;
  const toolCalls = lastMessage.tool_calls ?? [];

  // Run each requested tool in parallel and collect their results.
  const toolRegistry: Record<string, any> = {
    upsertFiles: fileTools.upsertFilesTool,
    listFiles: fileTools.listFilesTool,
    readFiles: fileTools.readFilesTool,
  };

  const toolResults = await Promise.all(
    toolCalls.map(async (toolCall) => {
      const tool = toolRegistry[toolCall.name] || fileTools[toolCall.name as keyof typeof fileTools];
      if (!tool) throw new Error(`Unknown tool: ${toolCall.name}`);
      const result = await (tool as any).invoke(toolCall);
      return new ToolMessage({
        tool_call_id: toolCall.id ?? "",
        content: typeof result === "string" ? result : JSON.stringify(result),
      });
    }),
  );

  // Append the tool outputs back into the message history.
  return {
    messages: [...state.messages, ...toolResults],
  };
}
